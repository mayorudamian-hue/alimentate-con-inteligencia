function renderAnnualSummary() {
  const rows = [];
  let totalInfPub = 0;
  let totalHorasAux = 0, totalHorasReg = 0, totalCursos = 0;
  let totalCursosAux = 0, totalCursosReg = 0, totalCursosPub = 0;
  const uniqueActiveNames = new Set();
  const uniqueAuxNames = new Set();
  const uniqueRegNames = new Set();

  MONTHS.forEach((mk, monthIdx) => {
    const d = DATA[mk];
    if (!d) return;
    totalInfPub += (d.publicadores||[]).filter(x => x.pred==='Sí').length;
    (d.publicadores||[]).forEach(p => {
      if (p.pred === 'Sí' && p.nombre) {
        const n = (p.nombre||'').trim();
        uniqueActiveNames.add(n);
      }
    });
    (d.precAux||[]).forEach(p => {
      if ((parseInt(p.horas)||0) > 0 && p.nombre) {
        const n = (p.nombre||'').trim();
        uniqueAuxNames.add(n);
        uniqueActiveNames.add(n);
      }
    });
    (d.precReg||[]).forEach(p => {
      if ((parseInt(p.horas)||0) > 0 && p.nombre) {
        const n = (p.nombre||'').trim();
        uniqueRegNames.add(n);
        uniqueActiveNames.add(n);
      }
    });
    totalHorasAux += (d.precAux||[]).reduce((s,p)=>s + (parseInt(p.horas)||0),0);
    totalHorasReg += (d.precReg||[]).reduce((s,p)=>s + (parseInt(p.horas)||0),0);
    totalCursosPub += (d.publicadores||[]).reduce((s,p)=>s + (parseInt(p.cursos)||0),0);
    totalCursosAux += (d.precAux||[]).reduce((s,p)=>s + (parseInt(p.cursos)||0),0);
    totalCursosReg += (d.precReg||[]).reduce((s,p)=>s + (parseInt(p.cursos)||0),0);
    totalCursos = totalCursosPub + totalCursosAux + totalCursosReg;

    (d.publicadores||[]).forEach(p => rows.push({
      monthIdx, mes: d.label, mesFull: d.date||d.label, nombre: p.nombre||'', tipo: 'Publicador',
      horas: null, pred: p.pred||'', cursos: p.cursos??'', obs: p.obs||''
    }));
    (d.precAux||[]).forEach(p => rows.push({
      monthIdx, mes: d.label, mesFull: d.date||d.label, nombre: p.nombre||'', tipo: 'Auxiliar',
      horas: p.horas??'', pred: '', cursos: p.cursos??'', obs: p.obs||''
    }));
    (d.precReg||[]).forEach(p => rows.push({
      monthIdx, mes: d.label, mesFull: d.date||d.label, nombre: p.nombre||'', tipo: 'Regular',
      horas: p.horas??'', pred: '', cursos: p.cursos??'', obs: p.obs||''
    }));
    (d.inactivos||[]).forEach(p => rows.push({
      monthIdx, mes: d.label, mesFull: d.date||d.label, nombre: p.nombre||'', tipo: 'Inactivo',
      horas: '', pred: '', cursos: '', obs: p.obs||''
    }));
  });

  const mesesContabilizados = MONTHS.filter(mk => {
    const d = DATA[mk];
    if (!d) return false;
    const hasPub = (d.publicadores||[]).some(p => p.pred === 'Sí');
    const hasAux = (d.precAux||[]).some(p => (parseInt(p.horas)||0) > 0);
    const hasReg = (d.precReg||[]).some(p => (parseInt(p.horas)||0) > 0);
    return hasPub || hasAux || hasReg;
  }).length;
  const divMeses = Math.max(1, mesesContabilizados);
  const avgCursos = totalCursos / divMeses;
  const avgCursosPub = totalCursosPub / divMeses;
  const avgCursosAux = totalCursosAux / divMeses;
  const avgCursosReg = totalCursosReg / divMeses;

  const q = normalizeStr(annualSearchQuery);
  const filtered = !q ? rows : rows.filter(r =>
    normalizeStr(r.nombre).includes(q) ||
    normalizeStr(r.obs).includes(q) ||
    normalizeStr(r.tipo).includes(q) ||
    normalizeStr(r.mes).includes(q) ||
    normalizeStr(r.mesFull).includes(q)
  );

  const tr = filtered
    .sort((a,b) => a.monthIdx-b.monthIdx || a.tipo.localeCompare(b.tipo,'es') || a.nombre.localeCompare(b.nombre,'es'))
    .map(r => `<tr>
      <td>${highlightText(r.mesFull, annualSearchQuery)}</td>
      <td><strong>${highlightText(r.nombre, annualSearchQuery)}</strong></td>
      <td>${r.tipo}</td>
      <td>${r.pred || '—'}</td>
      <td>${r.horas==='' ? '—' : r.horas}</td>
      <td>${r.cursos==='' ? '—' : r.cursos}</td>
      <td>${r.obs ? `<span class="obs-text obs-annual">${highlightText(r.obs, annualSearchQuery)}</span>${normalizeStr(r.obs).length > 45 ? '<button class="obs-toggle" onclick="toggleAnnualObs(this)">ver más</button>' : ''}` : ''}</td>
    </tr>`).join('');

  document.getElementById('content').innerHTML = `
    <div class="search-bar-wrap">
      <span class="search-icon">🔍</span>
      <input class="search-bar" type="text" placeholder="Buscar en todo el año (persona, observación, tipo o mes)..." oninput="applyAnnualSearch(this.value)" value="${annualSearchQuery||''}">
      ${annualSearchQuery ? '<button class="search-clear" onclick="clearAnnualSearch()">✕</button>' : ''}
    </div>
    <div class="summary-grid">
      <div class="stat-card c-active"><div class="stat-label">Publicadores Únicos</div><div class="stat-value">${uniqueActiveNames.size}</div><div class="stat-sub">Incluye publicadores con “Sí” y también auxiliares/regulares con horas > 0</div></div>
      <div class="stat-card c-aux"><div class="stat-label">Precursores Auxiliares</div><div class="stat-value">${uniqueAuxNames.size}</div><div class="stat-sub">Nombres únicos con horas > 0 · Prom. cursos: ${avgCursosAux.toFixed(1)} · Horas: ${totalHorasAux}</div></div>
      <div class="stat-card c-reg"><div class="stat-label">Precursores Regulares</div><div class="stat-value">${uniqueRegNames.size}</div><div class="stat-sub">Nombres únicos con horas > 0 · Prom. cursos: ${avgCursosReg.toFixed(1)} · Horas: ${totalHorasReg}</div></div>
      <div class="stat-card c-pubs"><div class="stat-label">Prom. Cursos Bíblicos</div><div class="stat-value">${avgCursos.toFixed(1)}</div><div class="stat-sub">Pub: ${avgCursosPub.toFixed(1)} · Aux: ${avgCursosAux.toFixed(1)} · Reg: ${avgCursosReg.toFixed(1)} · ${mesesContabilizados} meses</div></div>
    </div>
    <div class="section-title">Resumen Anual <span class="section-badge">${filtered.length} registros</span></div>
    <div class="table-wrap"><table>
      <thead><tr><th>Mes</th><th>Nombre</th><th>Tipo</th><th>Predicación</th><th>Horas</th><th>Cursos</th><th>Observaciones</th></tr></thead>
      <tbody>${tr || '<tr><td colspan="7" class="empty-section">Sin resultados para esta búsqueda.</td></tr>'}</tbody>
    </table></div>`;
}

