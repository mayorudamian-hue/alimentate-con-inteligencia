function importJSON(event) {
  const file = event.target.files[0];
  if (!file) return;
  const reader = new FileReader();
  reader.onload = function(e) {
    try {
      const parsed = JSON.parse(e.target.result);
      // Can be full DATA or single month
      let merged = 0;
      for (const key of MONTHS) {
        if (parsed[key]) {
          // Validate basic structure
          const m = parsed[key];
          if (Array.isArray(m.publicadores) && Array.isArray(m.precAux) && Array.isArray(m.precReg)) {
            DATA[key] = m;
            merged++;
          }
        }
      }
      if (merged === 0) {
        alert('El archivo JSON no tiene un formato válido o no contiene meses reconocibles.');
        return;
      }
      persist();
      render();
      toast(`${merged} mes${merged>1?'es':''} importado${merged>1?'s':''} ✓`);
    } catch(err) {
      alert('Error al leer el archivo JSON: ' + err.message);
    }
  };
  reader.readAsText(file);
}

