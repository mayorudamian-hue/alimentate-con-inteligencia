function openNombreModal(sec, idx, cur) {
  document.getElementById('modal-title').textContent = 'Editar nombre';
  document.getElementById('modal-body').innerHTML = `
    <div class="modal-field"><label>Apellido y Nombre</label>
    <input type="text" id="m-nombre" value="${cur.replace(/&quot;/g,'"')}" placeholder="Apellido, Nombre"></div>`;
  modalCb = () => {
    const v = document.getElementById('m-nombre').value.trim();
    if (v) {
      const dupe = checkDuplicateName(sec, idx, v);
      if (dupe) {
        if (!confirm(`Ya existe "${dupe}" con un nombre similar (diferencia de tildes). ¿Unificar ambos como "${v}"?`)) return;
        // Rename the duplicate to the new name too
        const list = arr(sec);
        list.forEach((p,i) => { if (i!==idx && normForDupe(p.nombre)===normForDupe(v)) p.nombre=v; });
      }
      arr(sec)[idx].nombre=v; sortByName(arr(sec)); persist(); render();
    }
    closeModal();
  };
  showModal();
  setTimeout(()=>{ const el=document.getElementById('m-nombre'); if(el){el.focus();el.select();} },60);
}

