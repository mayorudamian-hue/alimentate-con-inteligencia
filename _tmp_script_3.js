// ===================== PRECURSORES REGULARES — EXPORTAR =====================

function _precBuildData() {
  // Re-run the same logic as renderPrecView to get `people`
  const allNames = new Set();
  MONTHS.forEach(mk => {
    (DATA[mk]?.precReg||[]).forEach(p => { if(p.nombre) allNames.add(p.nombre); });
  });
  if (DATA._s21) {
    Object.keys(DATA._s21).forEach(nombre => {
      const s21rec = DATA._s21[nombre];
      const hasHoras = S21_ROWS.some((_, i) => {
        const slot = s21rec[String(i)];
        return slot && slot.horas !== null && slot.horas !== undefined && slot.horas > 0;
      });
      if (!hasHoras || allNames.has(nombre)) return;
      const inPadron = DATA._padron && Object.values(DATA._padron).find(p => p.nombre === nombre && p.rol === 'reg');
      if (inPadron) allNames.add(nombre);
    });
  }
  return [...allNames].sort((a,b) => a.localeCompare(b,'es')).map(nombre => {
    const s21rec = DATA._s21 && DATA._s21[nombre];
    const monthData = S21_ROWS.map((r, i) => {
      const s21slot = s21rec ? s21rec[String(i)] : null;
      const s21Horas = s21slot && s21slot.horas !== null && s21slot.horas !== undefined ? parseInt(s21slot.horas) : null;
      let monthHoras = null;
      if (r.appKey) {
        const md = DATA[r.appKey];
        const entry = (md?.precReg||[]).find(p => p.nombre === nombre);
        if (entry && entry.horas !== null && entry.horas !== undefined) monthHoras = parseInt(entry.horas) || 0;
      }
      const horas = monthHoras !== null ? monthHoras : s21Horas;
      return { label: r.label, horas };
    });
    const startIdx = getPrecRegStartIdx(nombre, monthData);
    const mesesObjetivoTotal = Math.max(1, 12 - startIdx);
    const metaObjetivo = mesesObjetivoTotal * 50;
    const reportedMonths = monthData.filter((m, idx) => idx >= startIdx && m.horas !== null);
    const totalHecho = reportedMonths.reduce((s,m) => s + m.horas, 0);
    const mesesReportados = reportedMonths.length;
    const mesesRestantes = Math.max(0, mesesObjetivoTotal - mesesReportados);
    const horasFaltantes = Math.max(0, metaObjetivo - totalHecho);
    const promHecho = mesesReportados > 0 ? Math.round(totalHecho / mesesReportados) : 0;
    const promNecesario = mesesRestantes > 0 ? Math.ceil(horasFaltantes / mesesRestantes) : 0;
    const pct = Math.min(100, Math.round((totalHecho / metaObjetivo) * 100));
    const esperado = 50 * mesesReportados;
    const diff = totalHecho - esperado;
    const statusTxt = mesesReportados === 0 ? 'Sin datos' : diff >= 0 ? 'En camino' : diff >= -50 ? 'Atención' : 'Atrasado';
    return { nombre, monthData, totalHecho, mesesReportados, mesesRestantes, horasFaltantes, promHecho, promNecesario, pct, diff, statusTxt, metaObjetivo, mesesObjetivoTotal, startIdx };
  });
}

