  if (!Number.isFinite(yearStart)) {
    const firstLabel = DATA[MONTHS[0]]?.label || MONTHS[0] || '';
    const m = firstLabel.match(/\b(20\d{2})\b/);
    if (m) yearStart = parseInt(m[1], 10);
  }
