// ── Sync all S-21 rows back to monthly records for a given person ────────────
function syncS21ToMonthly(nombre, rec) {
  if (!nombre || !rec) return;
  const nk = nombre.toLowerCase().trim();
  S21_ROWS.forEach((r, i) => {
    if (!r.appKey) return;
    const md = DATA[r.appKey]; if (!md) return;
    const s = rec[String(i)]; if (!s) return;

    const sections = [
      { key: 'precReg',      isPub: false },
      { key: 'precAux',      isPub: false },
      { key: 'publicadores', isPub: true  },
    ];

    let found = false;
    for (const { key, isPub } of sections) {
      const list = md[key] || [];
      const entry = list.find(p => (p.nombre||'').toLowerCase().trim() === nk);
      if (!entry) continue;
      found = true;
      if (!isPub) {
        // Always write — even if 0, so "0 horas" is valid
        if (s.horas !== null && s.horas !== undefined) entry.horas = s.horas;
        if (s.cursos !== null && s.cursos !== undefined) entry.cursos = s.cursos;
      } else {
        if (s.pred !== null && s.pred !== undefined) entry.pred = s.pred;
        if (s.cursos !== null && s.cursos !== undefined) entry.cursos = s.cursos;
      }
      break;
    }

    // If person not in any monthly list but has horas in S-21, auto-add to precReg
    if (!found && s.horas !== null && s.horas !== undefined && s.horas > 0) {
      if (!md.precReg) md.precReg = [];
      // Only add if they're a reg precursor (check padron or assume from context)
      const padronEntry = DATA._padron && Object.values(DATA._padron)
        .find(p => (p.nombre||'').toLowerCase().trim() === nk);
      const isReg = !padronEntry || padronEntry.rol === 'reg';
      if (isReg) {
        md.precReg.push({ nombre, horas: s.horas, cursos: s.cursos||null, obs: null });
        if (typeof sortByName === 'function') sortByName(md.precReg);
      }
    }
  });
}

