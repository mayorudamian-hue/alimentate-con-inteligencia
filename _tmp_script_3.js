function _normName(v) {
  return (v||'').toLowerCase().trim();
}

function getPrecRegStartIdx(nombre, monthData) {
  const nk = _normName(nombre);
  const regPresence = S21_ROWS.map((r, i) => {
    const byHoras = monthData[i]?.horas !== null && monthData[i]?.horas !== undefined;
    if (!r.appKey) return byHoras;
    const md = DATA[r.appKey];
    const byMonthly = (md?.precReg||[]).some(p => _normName(p.nombre) === nk);
    return byMonthly || byHoras;
  });

  const currentKey = MONTHS[currentIdx];
  const currentS21Idx = S21_ROWS.findIndex(r => r.appKey === currentKey);
  if (currentS21Idx !== -1 && regPresence[currentS21Idx]) {
    let start = currentS21Idx;
    while (start > 0 && regPresence[start - 1]) start--;
    return start;
  }

  const firstPresenceIdx = regPresence.findIndex(Boolean);
  return firstPresenceIdx === -1 ? 0 : firstPresenceIdx;
}

