function sortByName(a) {
  a.sort((x, y) => {
    const nx = (x.nombre||'').toLowerCase().trim();
    const ny = (y.nombre||'').toLowerCase().trim();
    if (!nx) return 1;   // empty names go to end
    if (!ny) return -1;
    return nx.localeCompare(ny, 'es');
  });
  // Re-number after sort
  a.forEach((item, i) => item.n = i + 1);
}

function renumber(a) {
  a.forEach((item, i) => item.n = i + 1);
}

function secToTipo(sec) {
  if (sec==='pub') return 'publicador';
  if (sec==='aux') return 'auxiliar';
  if (sec==='reg') return 'regular';
  return 'inactivo';
}

function tipoToSec(tipo) {
  if (tipo==='publicador') return 'pub';
  if (tipo==='auxiliar') return 'aux';
  if (tipo==='regular') return 'reg';
  return 'inac';
}

function toPubRow(p) {
  return { n:p.n||null, nombre:p.nombre||'', pred:p.pred??null, cursos:p.cursos??null, obs:p.obs??null };
}

function toPrecRow(p) {
  return { n:p.n||null, nombre:p.nombre||'', horas:p.horas??null, cursos:p.cursos??null, obs:p.obs??null };
}

function toInacRow(p) {
  return { n:p.n||null, nombre:p.nombre||'', obs:p.obs??null };
}

function normalizeByTipo(persona, tipoDestino) {
  if (tipoDestino==='publicador') return toPubRow(persona);
  if (tipoDestino==='auxiliar' || tipoDestino==='regular') return toPrecRow(persona);
  return toInacRow(persona);
}

function renderTipoSelect(sec, idx) {
  const tipoActual = secToTipo(sec);
  return `<select class="cell-select tipo-select tipo-${tipoActual}" onchange="updateTipoSelectClass(this);cambiarTipo('${sec}',${idx},this.value)">
    <option value="publicador" ${tipoActual==='publicador'?'selected':''}>Publicador</option>
    <option value="auxiliar" ${tipoActual==='auxiliar'?'selected':''}>Auxiliar</option>
    <option value="regular" ${tipoActual==='regular'?'selected':''}>Regular</option>
    <option value="inactivo" ${tipoActual==='inactivo'?'selected':''}>Inactivo</option>
  </select>`;
}

function updateTipoSelectClass(el) {
  if (!el) return;
  el.classList.remove('tipo-publicador','tipo-auxiliar','tipo-regular','tipo-inactivo');
  el.classList.add(`tipo-${el.value}`);
}

function cambiarTipo(secOrigen, idx, tipoDestino) {
  const tipoOrigen = secToTipo(secOrigen);
  if (tipoOrigen===tipoDestino) return;

  const origen = arr(secOrigen);
  const persona = origen[idx];
  if (!persona) return;

  origen.splice(idx, 1);
  renumber(origen);

  const secDestino = tipoToSec(tipoDestino);
  const destino = arr(secDestino);
  destino.push(normalizeByTipo(persona, tipoDestino));

  if (secDestino==='pub') renumber(destino);
  else sortByName(destino);

  persist();
  render();
}

function addRow(sec) {
  const a = arr(sec);
  let row;
  if (sec==='pub') row = {n:a.length+1,nombre:'',pred:null,cursos:null,obs:null};
  else if (sec==='inac') row = {n:a.length+1,nombre:'',obs:null};
  else row = {n:a.length+1,nombre:'',horas:null,cursos:null,obs:null};
  a.push(row);
  sortByName(a);
  persist();
  render();
}

function delRow(sec, idx) {
  if (!confirm('¿Eliminar esta fila?')) return;
  arr(sec).splice(idx,1);
  persist(); render();
}

function delNota(i) {
  DATA[MONTHS[currentIdx]].notas.splice(i,1);
  persist(); render();
}

function resetMonth() {
  const k = MONTHS[currentIdx];
  if (!confirm(`¿Resetear ${DATA[k].date}? Se perderán los cambios de este mes.`)) return;
  DATA[k] = BASE_DATA[k] ? JSON.parse(JSON.stringify(BASE_DATA[k])) : {label:DATA[k].label,date:DATA[k].date,notas:[],publicadores:[],precAux:[],precReg:[],inactivos:[]};
  persist(); render();
}

