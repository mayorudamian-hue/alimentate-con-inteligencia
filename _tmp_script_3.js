// Returns a Set of lowercase names that had "Sí" in a given window of month keys
function activeNamesInWindow(windowKeys) {
  const names = new Set();
  for (const k of windowKeys) {
    const m = DATA[k];
    if (!m) continue;
    for (const p of m.publicadores) {
      if (p.pred === 'Sí' && p.nombre) names.add(p.nombre.toLowerCase().trim());
    }
  }
  return names;
}

// For each publisher in current month, determine their status:
// "active"  — had Sí in last 6 months (window: pos-5 to pos, inclusive)
// "warning" — exactly 6 months since last Sí (the 6th month with no Sí) → show badge
// "inactive"— 7+ months without Sí → should appear in inactivos list
function getPubStatuses(currentKey) {
  const pos = MONTHS.indexOf(currentKey);
  const d = DATA[currentKey];
  const statuses = {};

  for (const p of d.publicadores) {
    if (!p.nombre) { statuses[p.nombre] = 'active'; continue; }
    const name = p.nombre.toLowerCase().trim();
    // Check last 6 months (pos-5 to pos inclusive = 6 months)
    const window6 = MONTHS.slice(Math.max(0, pos - 5), pos + 1);
    const active6 = activeNamesInWindow(window6);
    if (active6.has(name)) { statuses[name] = 'active'; continue; }

    // Not active in 6 months. Are we in exactly month 7 (show warning)?
    // i.e. did they have a Sí exactly 7 months ago (pos-6)?
    if (pos >= 6) {
      const window7 = MONTHS.slice(Math.max(0, pos - 6), pos - 5 + 1); // just month pos-6
      const had7ago = activeNamesInWindow(window7);
      if (had7ago.has(name)) { statuses[name] = 'warning'; continue; }
    }
    statuses[name] = 'inactive';
  }
  return statuses;
}

function getActivePubCount(currentKey) {
  const pos = MONTHS.indexOf(currentKey);
  if (pos < 0) return 0;
  const windowKeys = MONTHS.slice(Math.max(0, pos - 5), pos + 1);
  const d = DATA[currentKey] || {};
  const candidates = new Set();
  [...(d.publicadores||[]), ...(d.precAux||[]), ...(d.precReg||[])].forEach(p => {
    const n = (p.nombre||'').toLowerCase().trim();
    if (n) candidates.add(n);
  });

  const hasReportInMonth = (mk, nameKey) => {
    const md = DATA[mk];
    if (!md) return false;
    const pub = (md.publicadores||[]).some(p => (p.nombre||'').toLowerCase().trim()===nameKey && p.pred==='Sí');
    if (pub) return true;
    const aux = (md.precAux||[]).some(p => (p.nombre||'').toLowerCase().trim()===nameKey && (parseInt(p.horas)||0) > 0);
    if (aux) return true;
    const reg = (md.precReg||[]).some(p => (p.nombre||'').toLowerCase().trim()===nameKey && (parseInt(p.horas)||0) > 0);
    return reg;
  };

  let total = 0;
  candidates.forEach(nameKey => {
    if (windowKeys.some(mk => hasReportInMonth(mk, nameKey))) total++;
  });
  return total;
}

function countPrecReports(list) {
  return (list||[]).filter(p => (parseInt(p.horas)||0) > 0).length;
}

function resumen(key) {
  const d = DATA[key];
  if (!d.inactivos) d.inactivos = [];
  const informesPub = d.publicadores.filter(x => x.pred==='Sí').length;
  const a = countPrecReports(d.precAux), r = countPrecReports(d.precReg);
  const activePubs = getActivePubCount(key);
  return { activos: activePubs, informesPub, informesAux: a, informesReg: r };
}
function sumField(arr, f) { return arr.reduce((s,x) => s + (parseInt(x[f])||0), 0); }
function hasData(k) { const d=DATA[k]; return d.publicadores.length||d.precAux.length||d.precReg.length; }
