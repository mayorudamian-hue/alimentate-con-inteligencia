// Normalize name for duplicate detection (remove accents, lowercase)
function normForDupe(s) { return normalizeStr(s); }

function checkDuplicateName(sec, idx, newName) {
  // Returns name of existing entry if duplicate found (ignoring accents), null otherwise
  const list = arr(sec);
  const norm = normForDupe(newName);
  const dupe = list.find((p, i) => i !== idx && normForDupe(p.nombre) === norm);
  return dupe ? dupe.nombre : null;
}

