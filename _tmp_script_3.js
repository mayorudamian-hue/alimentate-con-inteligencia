// ── Download all charts as a single PNG (stacked) ─────────────────────────
function downloadAllCharts() {
  const y = getServiceYearInfo();
  const ids = ['chart-informes','chart-horas','chart-activos','chart-cursos','chart-asistencia'];
  const canvases = ids.map(id => document.getElementById(id)).filter(Boolean);
  if (!canvases.length) return;

  const gap = 20;
  const totalW = Math.max(...canvases.map(c => c.width));
  const totalH = canvases.reduce((s,c) => s + c.height, 0) + gap * (canvases.length - 1) + 80;

  const out = document.createElement('canvas');
  out.width = totalW;
  out.height = totalH;
  const ctx = out.getContext('2d');
  ctx.fillStyle = '#f7f4ef';
  ctx.fillRect(0, 0, totalW, totalH);

  // Title
  ctx.fillStyle = '#1a2744';
  ctx.font = 'bold 22px Arial';
  ctx.textAlign = 'center';
  ctx.fillText(`Informe de Actividad — ${y.congName}`, totalW / 2, 36);
  ctx.font = '14px Arial';
  ctx.fillStyle = '#9e9585';
  ctx.fillText(`Resumen General ${y.span}`, totalW / 2, 58);

  let y = 72;
  canvases.forEach(c => {
    ctx.drawImage(c, (totalW - c.width) / 2, y);
    y += c.height + gap;
  });

  const link = document.createElement('a');
  const safeCong = y.congName.replace(/[^a-zA-ZáéíóúÁÉÍÓÚñÑ0-9,_ -]/g,'').trim().replace(/\s+/g,'_');
  link.download = `${safeCong}_Graficos_Completos_${y.short}.png`;
  link.href = out.toDataURL('image/png');
  link.click();
}


