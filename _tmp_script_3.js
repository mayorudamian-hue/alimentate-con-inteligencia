function isPredYes(v) {
  return v === 'Sí' || v === 'Si' || v === 'SÃ­';
}

function ensureS21(nombre) {
  if (!DATA._s21) DATA._s21 = {};
  const k = nombre.trim();
  if (!DATA._s21[k]) DATA._s21[k] = { meta: {} };
  S21_ROWS.forEach((_,i) => {
    const slot = String(i);
    if (!DATA._s21[k][slot]) DATA._s21[k][slot] = { pred:null, cursos:null, aux:false, horas:null, notas:'' };
  });
  if (!DATA._s21[k].meta) DATA._s21[k].meta = {};
  return DATA._s21[k];
}

function syncS21FromReports(nombre, rec) {
  const nk = nombre.toLowerCase().trim();
  S21_ROWS.forEach((r, i) => {
    if (!r.appKey) return;
    const md = DATA[r.appKey]; if (!md) return;
    const s = rec[String(i)];
    const pub = md.publicadores.find(p => (p.nombre||'').toLowerCase().trim()===nk);
    if (pub) {
      if (s.pred===null) s.pred = pub.pred;
      if (s.cursos===null && pub.cursos) s.cursos = pub.cursos;
    }
    const ax = md.precAux.find(p => (p.nombre||'').toLowerCase().trim()===nk);
    if (ax) {
      if (s.pred===null) s.pred='Sí';
      s.aux=true;
      if (s.horas===null && ax.horas) s.horas=ax.horas;
      if (s.cursos===null && ax.cursos) s.cursos=ax.cursos;
    }
    const rg = md.precReg.find(p => (p.nombre||'').toLowerCase().trim()===nk);
    if (rg) {
      if (s.pred===null) s.pred='Sí';
      if (s.horas===null && rg.horas) s.horas=rg.horas;
      if (s.cursos===null && rg.cursos) s.cursos=rg.cursos;
    }
  });
}

